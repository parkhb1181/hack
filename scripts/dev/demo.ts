/* ------------------------------ 형식 변환 ------------------------------ */

const WEEK = ['일', '월', '화', '수', '목', '금', '토']
const pad = (n: number) => String(n).padStart(2, '0')

function ampm(h: number, m: number): string {
  const period = h < 12 ? '오전' : '오후'
  const h12 = h % 12 === 0 ? 12 : h % 12
  return `${period} ${h12}:${pad(m)}`
}

const out: string[] = [
  // 제목 줄의 이름이 '상대'다 — 나머지 한 명이 '나'가 된다(SPEC §3.10)
  `${OTHER} 님과 카카오톡 대화`,
  '저장한 날짜 : 2026-08-05 12:00:00',
  '',
]

let lastDate = ''
let count = 0
let deleted = 0

for (const day of DAYS) {
  if (day.date !== lastDate) {
    lastDate = day.date
    const [y, mo, d] = day.date.split('-').map(Number)
    const dow = WEEK[new Date(Date.UTC(y, mo - 1, d)).getUTCDay()]
    out.push(`--------------- ${y}년 ${mo}월 ${d}일 ${dow}요일 ---------------`)
  }

  const [sh, sm] = day.start.split(':').map(Number)
  let cursor = sh * 60 + sm

  for (const [who, gap, text] of day.lines) {
    cursor += gap
    const h = Math.floor(cursor / 60) % 24
    const m = cursor % 60

    // 삭제 메시지는 **이름·시각 접두어 없이 홑줄로** 나온다. 실물 내보내기가
    // 그렇고(원본 253건이 이 형태였다), 파서도 그 형태만 삭제로 센다.
    // 말풍선 줄에 넣으면 그냥 본문이 "메시지가 삭제되었습니다."인 발화가 된다.
    if (text === '메시지가 삭제되었습니다.') {
      out.push(text)
      deleted++
      continue
    }

    const name = who === '나' ? ME : OTHER
    out.push(`[${name}] [${ampm(h, m)}] ${text}`)
    count++
  }
}

// ⚠️ 레코드 구분자는 **CRLF**다. 메시지 안의 줄바꿈은 LF로 남는다 —
// 카카오톡 PC 내보내기가 그렇게 구분하고, `splitRecords`도 `\r\n`으로만 자른다.
// LF로 쓰면 파일 전체가 레코드 1개가 되어 아무것도 안 읽힌다(실측).
const dest = join(process.cwd(), 'fixtures', 'seeds', 'demo_crush.txt')
writeFileSync(dest, out.join('\r\n'), 'utf8')

